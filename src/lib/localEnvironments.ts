import { stringify } from "smol-toml";
import type {
  LocalEnvironment,
  LocalEnvironmentResult,
} from "../../packages/app-server-client/src/protocol";

export const environmentPlatforms = ["darwin", "linux", "win32"] as const;
export type EnvironmentPlatform = (typeof environmentPlatforms)[number];
export type EnvironmentScriptPlatform = EnvironmentPlatform | "default";
export type EnvironmentActionIcon = "tool" | "run" | "debug" | "test";

export interface EnvironmentActionDraft {
  id: string;
  name: string;
  command: string;
  icon: EnvironmentActionIcon | null;
  platform: EnvironmentPlatform | null;
}

export interface LocalEnvironmentDraft {
  version: number;
  name: string;
  setupScript: string;
  setupPlatformScripts: Record<EnvironmentPlatform, string>;
  cleanupScript: string;
  cleanupPlatformScripts: Record<EnvironmentPlatform, string>;
  actions: EnvironmentActionDraft[];
}

function platformScripts(lifecycle?: LocalEnvironment["setup"] | null) {
  return Object.fromEntries(
    environmentPlatforms.map((platform) => [
      platform,
      lifecycle?.[platform]?.script ?? "",
    ]),
  ) as Record<EnvironmentPlatform, string>;
}

export function createLocalEnvironmentDraft(
  environment?: LocalEnvironment | null,
  defaultName = "",
): LocalEnvironmentDraft {
  return {
    version: environment?.version ?? 1,
    name: environment?.name ?? defaultName,
    setupScript: environment?.setup.script ?? "",
    setupPlatformScripts: platformScripts(environment?.setup),
    cleanupScript: environment?.cleanup?.script ?? "",
    cleanupPlatformScripts: platformScripts(environment?.cleanup),
    actions: (environment?.actions ?? []).map((action) => ({
      ...action,
      id: crypto.randomUUID(),
      icon: action.icon ?? null,
      platform: action.platform ?? null,
    })),
  };
}

export function createEnvironmentAction(): EnvironmentActionDraft {
  return {
    id: crypto.randomUUID(),
    name: "",
    command: "",
    icon: "tool",
    platform: null,
  };
}

export function validateLocalEnvironmentDraft(draft: LocalEnvironmentDraft) {
  return {
    missingName: !draft.name.trim(),
    incompleteActionIds: draft.actions
      .filter(
        (action) =>
          Boolean(action.name.trim()) !== Boolean(action.command.trim()),
      )
      .map((action) => action.id),
  };
}

function lifecycle(
  script: string,
  overrides: Record<EnvironmentPlatform, string>,
) {
  return {
    script,
    ...Object.fromEntries(
      environmentPlatforms
        .filter((platform) => overrides[platform].length > 0)
        .map((platform) => [platform, { script: overrides[platform] }]),
    ),
  };
}

export function serializeLocalEnvironment(
  draft: LocalEnvironmentDraft,
): string {
  const validation = validateLocalEnvironmentDraft(draft);
  if (validation.missingName || validation.incompleteActionIds.length) {
    throw new Error("Incomplete local environment");
  }
  const cleanup = lifecycle(draft.cleanupScript, draft.cleanupPlatformScripts);
  return (
    "# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY\n" +
    stringify({
      version: draft.version,
      name: draft.name.trim(),
      setup: lifecycle(draft.setupScript, draft.setupPlatformScripts),
      ...(Object.keys(cleanup).length > 1 || draft.cleanupScript
        ? { cleanup }
        : {}),
      actions: draft.actions
        .filter((action) => action.name.trim() && action.command.trim())
        .map((action) => ({
          name: action.name.trim(),
          command: action.command.trim(),
          ...(action.icon ? { icon: action.icon } : {}),
          ...(action.platform ? { platform: action.platform } : {}),
        })),
    })
  );
}

export function defaultEnvironmentConfigPath(workspaceRoot: string): string {
  const separator = workspaceRoot.includes("\\") ? "\\" : "/";
  return `${workspaceRoot.replace(/[\\/]+$/, "")}${separator}.codex${separator}environments${separator}environment.toml`;
}

export function environmentWorkspaceRoot(configPath: string): string {
  return configPath.replace(/[\\/]\.codex[\\/]environments[\\/][^\\/]+$/, "");
}

export function partitionLocalEnvironments(
  entries: LocalEnvironmentResult[],
  workspaceRoot: string,
) {
  const normalize = (path: string) => {
    const normalized = path.replaceAll("\\", "/").replace(/\/+$/, "");
    return /^(?:[a-z]:|\/\/)/i.test(normalized)
      ? normalized.toLowerCase()
      : normalized;
  };
  const projectEnvironments: LocalEnvironmentResult[] = [];
  const inheritedEnvironments: LocalEnvironmentResult[] = [];
  const root = normalize(workspaceRoot);
  for (const entry of entries) {
    (normalize(environmentWorkspaceRoot(entry.configPath)) === root
      ? projectEnvironments
      : inheritedEnvironments
    ).push(entry);
  }
  return { projectEnvironments, inheritedEnvironments };
}

export function effectiveEnvironmentScript(
  draft: LocalEnvironmentDraft,
  type: "setup" | "cleanup",
  platform: EnvironmentScriptPlatform,
) {
  const fallback = draft[`${type}Script`];
  return platform === "default"
    ? fallback
    : draft[`${type}PlatformScripts`][platform] || fallback;
}
